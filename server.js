const express = require('express');

const app = express();
const PORT = 3000;

//Part 3 - Create Your Data
const cars = [
    { id: 1, make: "Mercedes Benz", model: "C63 AMG", year: "2012." }, 
    { id: 2, make: "Ford", model: "GT 350", year: "2015." },
    { id: 3, make: "Porsche", model: "Taycan", year: "2021." },
    { id: 4, make: "Chevrolet", model: "Corvette 3LT Convertible", year: "2023." },
    { id: 5, make: "BMW", model: "i4 M50", year: "2024." }
];

app.use(express.json());
app.use(express.static("public"));

//Part 6 - Add Middleware
app.use((req, res, next) => {
    console.log(`${req.method} ${req.url}`);
    next();
});

app.get("/about", (req, res) => {
    res.send(`
        <h1>About the Car Portal</h1>
        <p>This page was generated by Express.</p>
        <p><a ref="/">Return Home</a></p>
    `);
});

//Part 4 - Create an API Route
app.get("/api/cars", (req, res) => {
    res.json(cars);
});

//Part 5 - Create a Route Parameter
app.get("/api/cars/:id", (req, res) => {
    const id = Number(req.params.id);
    const car = cars.find(car => car.id === id);

    if (!car) {
        return res.status(404).json({ message: "Car not found" });
    }
    res.json(car);
});

app.listen(PORT, () => {
    console.log(`Car Portal running on http://localhost:${PORT}`);
});